#!/usr/bin/env python3
"""LIVE Release 2 with the CID:IQ exponents transferred verbatim.

Nothing is fitted on LIVE except the scalar ppd that the sweep selects, so
these numbers are directly comparable to SSIM and MS-SSIM, which have no
fitted parameters either.
"""
import os, sys
import numpy as np
from scipy.optimize import curve_fit
from scipy.stats import spearmanr, kendalltau

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PPDS = [15, 20, 25, 30, 40, 55, 80, 110]

def vqeg(x, b1, b2, b3, b4, b5):
    return b1 * (0.5 - 1.0 / (1.0 + np.exp(b2 * (x - b3)))) + b4 * x + b5

def stats(x, y):
    x, y = np.asarray(x, float), np.asarray(y, float)
    best, bp = -1, None
    for sc in (0.02, 0.2, 1.0, 5.0, 20.0, 100.0):
        for sg in (1, -1):
            try:
                p, _ = curve_fit(vqeg, x, y, maxfev=200000,
                                 p0=[y.max()-y.min(), sg*sc, x.mean(), 0.0, y.mean()])
                pr = vqeg(x, *p)
                if np.all(np.isfinite(pr)):
                    r = abs(np.corrcoef(pr, y)[0, 1])
                    if r > best: best, bp = r, p
            except Exception:
                pass
    return (best, abs(spearmanr(x, y).statistic), abs(kendalltau(x, y).statistic),
            float(np.sqrt(np.mean((vqeg(x, *bp) - y) ** 2))))

def load(path, cols=(3, 4, 5, 6)):
    out = []
    for line in open(path):
        if line.startswith('#') or line.startswith('ref,'):
            continue
        f = line.rstrip('\n').split(',')
        out.append(tuple(float(f[c]) for c in cols))
    return out

base = load(f"{ROOT}/runs/live_base.csv", (3, 4, 5))
y = [r[0] for r in base]
ss = stats([r[1] for r in base], y)
ms = stats([r[2] for r in base], y)
print("n = %d pairs" % len(base))
print("SSIM     PLCC %.4f  SRCC %.4f  KRCC %.4f  RMSE %.3f" % ss)
print("MS-SSIM  PLCC %.4f  SRCC %.4f  KRCC %.4f  RMSE %.3f" % ms)

res = {}
for P in PPDS:
    rows = load(f"{ROOT}/runs/liveU_{P}.csv", (3, 6))
    assert len(rows) == len(base), (P, len(rows))
    res[P] = stats([r[1] for r in rows], [r[0] for r in rows])
    print("MB-SSIM ppd %-4d PLCC %.4f  SRCC %.4f  KRCC %.4f  RMSE %.3f" % ((P,) + res[P]))

bestP = max(PPDS, key=lambda p: res[p][0])
print("\nbest ppd = %d" % bestP)

def rowfmt(idx, better_high, fmt="%.4f"):
    cells = []
    allv = [res[p][idx] for p in PPDS] + [ss[idx], ms[idx]]
    win = max(allv) if better_high else min(allv)
    for p in PPDS:
        v = res[p][idx]
        cells.append((r"\textbf{" + fmt + "}") % v if v == win else fmt % v)
    return " & ".join(cells)

def scal(v, idx, better_high, fmt="%.4f"):
    allv = [res[p][idx] for p in PPDS] + [ss[idx], ms[idx]]
    win = max(allv) if better_high else min(allv)
    return (r"\textbf{" + fmt + "}") % v if v == win else fmt % v

nb = {15: 4, 20: 5, 25: 5, 30: 5, 40: 6, 55: 6, 80: 6, 110: 6}
print("\n%% --- generated by scripts/live_untuned_summary.py ---")

def cell(v, idx, better_high, fmt):
    allv = [res[p][idx] for p in PPDS] + [ss[idx], ms[idx]]
    win = max(allv) if better_high else min(allv)
    return (r"\textbf{" + fmt + "}") % v if v == win else fmt % v

body = []
for p in PPDS:
    body.append(r"$%d$ & %d & %s & %s & %s \\" %
                (p, nb[p],
                 cell(res[p][0], 0, True,  "%.4f"),
                 cell(res[p][1], 1, True,  "%.4f"),
                 cell(res[p][3], 3, False, "%.2f")))
body.append(r"\midrule")
body.append(r"\multicolumn{2}{@{}l}{SSIM (no geometry input)} & %s & %s & %s \\" %
            (cell(ss[0], 0, True, "%.4f"), cell(ss[1], 1, True, "%.4f"),
             cell(ss[3], 3, False, "%.2f")))
body.append(r"\multicolumn{2}{@{}l}{MS-SSIM (no geometry input)} & %s & %s & %s \\" %
            (cell(ms[0], 0, True, "%.4f"), cell(ms[1], 1, True, "%.4f"),
             cell(ms[3], 3, False, "%.2f")))
print(r"\newcommand{\LIVEbody}{%")
print("\n".join(body))
print("}")
print(r"\newcommand{\LIVEbestppd}{%d}" % bestP)
