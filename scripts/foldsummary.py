#!/usr/bin/env python3
"""Mean held-out numbers from an nbsjoint cross-validation log, plus the
matching SSIM / MS-SSIM baselines on the same folds, as LaTeX macros."""
import re, sys, subprocess, os, csv

LOG   = sys.argv[1] if len(sys.argv) > 1 else "runs/fit_pooled.log"
BENCH = "runs"
FOLDS = 5

def nb_folds(path):
    d = {"50cm": [], "100cm": [], "pooled": []}
    on = False
    for L in open(path):
        if L.startswith("5-fold"):
            on = True; continue
        if "mean held-out" in L or L.startswith("final"):
            break
        if not on:
            continue
        m = re.match(r"\s+(50cm|100cm|pooled)\s+n=\s*(\d+)\s+PLCC\s+([\d.]+)\s+SRCC\s+([\d.]+)", L)
        if m:
            d[m.group(1)].append((float(m.group(3)), float(m.group(4))))
    return d

def load(path):
    rows = []
    for line in open(path):
        if line.startswith('#') or line.startswith('ref,'):
            continue
        f = line.rstrip('\n').split(',')
        rows.append((f[2], float(f[3]), float(f[4]), float(f[5])))
    return rows

b50, b100 = load(f"{BENCH}/cidiq_50cm.csv"), load(f"{BENCH}/cidiq_100cm.csv")
gid, g = {}, []
for r in b50:
    gid.setdefault(r[0], len(gid)); g.append(gid[r[0]])

import numpy as np
from scipy.optimize import curve_fit
from scipy.stats import spearmanr

def vqeg(x, b1, b2, b3, b4, b5):
    return b1 * (0.5 - 1.0 / (1.0 + np.exp(b2 * (x - b3)))) + b4 * x + b5

def ps(x, y):
    x, y = np.asarray(x), np.asarray(y)
    best = None
    for sc in (1.0, 5.0, 20.0, 60.0):
        try:
            p, _ = curve_fit(vqeg, x, y, maxfev=200000,
                             p0=[y.max() - y.min(), sc, x.mean(), 0.0, y.mean()])
            pr = vqeg(x, *p)
            if np.all(np.isfinite(pr)):
                r = abs(np.corrcoef(pr, y)[0, 1])
                if best is None or r > best: best = r
        except Exception:
            pass
    return (best if best else 0.0), abs(spearmanr(x, y).statistic)

def baseline(col):
    out = {"50cm": [], "100cm": [], "pooled": []}
    for f in range(FOLDS):
        sel = [k for k, x in enumerate(g) if x % FOLDS == f]
        s5, m5 = [b50[k][col] for k in sel],  [b50[k][1] for k in sel]
        s1, m1 = [b100[k][col] for k in sel], [b100[k][1] for k in sel]
        out["50cm"].append(ps(s5, m5))
        out["100cm"].append(ps(s1, m1))
        out["pooled"].append(ps(s5 + s1, m5 + m1))
    return out

def mean(v):
    return (sum(a for a, _ in v) / len(v), sum(b for _, b in v) / len(v))

nb = nb_folds(LOG)
ss, ms = baseline(2), baseline(3)
print("%-9s %-16s %-16s %-16s" % ("", "50 cm", "100 cm", "pooled"))
rows = {}
for name, d in (("SSIM", ss), ("MS-SSIM", ms), ("NB-SSIM", nb)):
    cells = []
    for c in ("50cm", "100cm", "pooled"):
        if len(d[c]) < FOLDS:
            cells.append("(incomplete %d)" % len(d[c])); continue
        p, s = mean(d[c]); rows[(name, c)] = (p, s)
        cells.append("%.4f / %.4f" % (p, s))
    print("%-9s %-16s %-16s %-16s" % (name, *cells))

if all((n, c) in rows for n in ("SSIM", "MS-SSIM", "NB-SSIM")
       for c in ("50cm", "100cm", "pooled")):
    tag = {"50cm": "Fifty", "100cm": "Hund", "pooled": "Pool"}
    pre = {"SSIM": "ss", "MS-SSIM": "ms", "NB-SSIM": "fit"}
    print("\n%% --- generated by scripts/foldsummary.py from %s ---" % LOG)
    for n in ("SSIM", "MS-SSIM", "NB-SSIM"):
        for c in ("50cm", "100cm", "pooled"):
            p, s = rows[(n, c)]
            print("\\newcommand{\\%s%sP}{%.4f}   \\newcommand{\\%s%sS}{%.4f}"
                  % (pre[n], tag[c], p, pre[n], tag[c], s))
